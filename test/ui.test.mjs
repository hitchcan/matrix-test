test('工作台UI：小红书图文与抖音视频目标、预览及独立文案可用',async t=>{
  const dir=mkdtempSync(join(tmpdir(),'matrix-ui-test-'));
  let opened=false;
  const studio=createStudio({dataDir:dir,browserRuntime:{open:async()=>{opened=true;},check:async()=>({platformId:'fixture-user'}),disconnect:async()=>{},close:async()=>{}}});
  await new Promise(r=>studio.server.listen(0,'127.0.0.1',r));
  const browser=await chromium.launch({channel:process.env.MATRIX_BROWSER_CHANNEL||'chrome',headless:true});
  t.after(async()=>{await browser.close();await studio.close();const target=resolve(dir);if(dirname(target)!==resolve(tmpdir())||!basename(target).startsWith('matrix-ui-test-')) throw Error('测试目录无效');rmSync(target,{recursive:true,force:true});});
  const page=await browser.newPage({viewport:{width:1360,height:900}});
  page.setDefaultTimeout(10000);
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto(`http://127.0.0.1:${studio.server.address().port}/#accounts`);
  await page.getByPlaceholder('例如：我的 B站主账号').fill('联调示例账号（测试数据）');
  await page.getByRole('button',{name:'添加账号',exact:true}).click();
  await page.getByRole('button',{name:'登录 / 打开后台',exact:true}).waitFor();
  await page.getByRole('button',{name:'登录 / 打开后台',exact:true}).click();
  assert.equal(opened,true);
  assert.equal(await page.getByRole('button',{name:'核验身份',exact:true}).count(),0);
  await page.getByText('已登录，可发布',{exact:true}).waitFor();
  assert.equal(await page.getByRole('option',{name:'小红书'}).count(),1);
  assert.equal(await page.getByRole('option',{name:'抖音',exact:true}).count(),1);
  await page.locator('select[name="platform"]').selectOption('xhs');
  await page.getByPlaceholder('例如：我的 B站主账号').fill('小红书界面测试');await page.getByRole('button',{name:'添加账号',exact:true}).click();
  await page.getByRole('heading',{name:'小红书界面测试',exact:true}).waitFor();
  await page.locator('select[name="platform"]').selectOption('douyin');
  await page.getByPlaceholder('例如：我的 B站主账号').fill('抖音界面测试');await page.getByRole('button',{name:'添加账号',exact:true}).click();
  await page.getByRole('heading',{name:'抖音界面测试',exact:true}).waitFor();
  await page.screenshot({path:fileURLToPath(new URL('../docs/账号接入界面.png',import.meta.url)),fullPage:true});
  await page.getByRole('link',{name:'▧ 内容工作室 ＋',exact:true}).click();await page.getByRole('tab',{name:'▧　图片笔记',exact:true}).click();
  assert.equal(await page.getByRole('checkbox',{name:'选择 小红书界面测试',exact:true}).isEnabled(),true);
  assert.equal(await page.getByRole('checkbox',{name:'选择 抖音界面测试',exact:true}).isDisabled(),true);
  await page.screenshot({path:fileURLToPath(new URL('../docs/小红书图片笔记入口.png',import.meta.url)),fullPage:true});
  await page.getByRole('tab',{name:'▷　视频',exact:true}).click();
  assert.equal(await page.getByRole('checkbox',{name:'选择 抖音界面测试',exact:true}).isEnabled(),true);
  await page.locator('button[data-preview="douyin"]').click();
  assert.match(await page.locator('#preview').innerText(),/抖音/);
  assert.equal(await page.locator('[data-field="versions.douyin.title"]').count(),1);
  await page.getByRole('checkbox',{name:'选择 联调示例账号（测试数据）',exact:true}).check();
  await page.getByLabel('平台 AI 辅助创作声明',{exact:true}).selectOption('no');
  assert.match(await page.locator('#publication-help').innerText(),/知乎将核对声明/);
  await page.getByLabel('平台 AI 辅助创作声明',{exact:true}).selectOption('yes');
  assert.doesNotMatch(await page.locator('#publication-help').innerText(),/知乎将核对声明/);
  await page.screenshot({path:fileURLToPath(new URL('../docs/抖音视频发布入口.png',import.meta.url)),fullPage:true});
  assert.deepEqual(errors,[]);
});

test('富文本UI：Word样式粘贴、草稿保存和恢复保留标题、加粗、表格及对齐',async t=>{
  const dir=mkdtempSync(join(tmpdir(),'matrix-ui-test-'));
  const studio=createStudio({dataDir:dir});await new Promise(r=>studio.server.listen(0,'127.0.0.1',r));
  const browser=await chromium.launch({channel:process.env.MATRIX_BROWSER_CHANNEL||'chrome',headless:true});
  t.after(async()=>{await browser.close();await studio.close();const target=resolve(dir);if(dirname(target)!==resolve(tmpdir())||!basename(target).startsWith('matrix-ui-test-'))throw Error('测试目录无效');rmSync(target,{recursive:true,force:true});});
  const origin=`http://127.0.0.1:${studio.server.address().port}`;
  const context=await browser.newContext({viewport:{width:1360,height:1000},permissions:['clipboard-read','clipboard-write']});
  const page=await context.newPage();page.setDefaultTimeout(10000);
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto(origin);await page.getByRole('tab',{name:'▤　长文章',exact:true}).click();
  await page.getByPlaceholder('给这次创作一个好标题').fill('Word格式测试文章');
  const editor=page.getByRole('textbox',{name:'文章正文',exact:true});
  await editor.click();
  await page.evaluate(async()=>navigator.clipboard.write([new ClipboardItem({'text/html':new Blob(['<h2>保留标题</h2><p style="text-align:center"><strong>保留加粗</strong> 和 <em>斜体</em></p><table><tr><td><p>项目</p></td><td><p>说明</p></td></tr></table><ul><li><p>列表项目</p></li></ul>'],{type:'text/html'})})]));
  await editor.press('ControlOrMeta+V');
  await editor.locator('strong').waitFor();assert.equal(await editor.locator('h2').innerText(),'保留标题');
  assert.equal(await page.getByLabel('静默执行自动发布',{exact:true}).isDisabled(),true);
  await page.getByLabel('发布方式',{exact:true}).selectOption('auto');
  assert.equal(await page.getByLabel('静默执行自动发布',{exact:true}).isEnabled(),true);
  await page.getByLabel('静默执行自动发布',{exact:true}).uncheck();
  await page.getByLabel('静默执行自动发布',{exact:true}).check();
  await page.getByLabel('平台 AI 辅助创作声明',{exact:true}).selectOption('yes');
  await page.getByRole('button',{name:'保存草稿',exact:true}).click();
  let state=await fetch(origin+'/api/state').then(r=>r.json());
  assert.match(state.drafts[0].bodyHtml,/<strong>保留加粗/);assert.match(state.drafts[0].bodyHtml,/<table/);assert.match(state.drafts[0].bodyHtml,/text-align:\s*center/);
  assert.deepEqual(state.drafts[0].publication,{mode:'auto',aiAssisted:true,silent:true});
  await page.reload();await page.getByRole('button',{name:/草稿箱/}).click();await page.getByRole('button',{name:'继续编辑',exact:true}).click();
  assert.equal(await page.getByRole('textbox',{name:'文章正文',exact:true}).locator('strong').innerText(),'保留加粗');
  assert.equal(await page.getByLabel('发布方式',{exact:true}).inputValue(),'auto');
  assert.equal(await page.getByLabel('平台 AI 辅助创作声明',{exact:true}).inputValue(),'yes');
  await page.screenshot({path:fileURLToPath(new URL('../docs/富文本编辑器.png',import.meta.url)),fullPage:true});
  await page.screenshot({path:fileURLToPath(new URL('../docs/发布选项.png',import.meta.url)),fullPage:true});
  await page.getByRole('button',{name:'创建并直接发布 ↗',exact:true}).click();
  await page.getByRole('heading',{name:'分发任务',exact:true}).waitFor();
  await page.getByRole('button',{name:'查看 / 处理',exact:true}).first().click();
  await page.getByText('工具直接完成发布 · AI辅助创作：勾选',{exact:true}).waitFor();
  assert.deepEqual(errors,[]);
});
